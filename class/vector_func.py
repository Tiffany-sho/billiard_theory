"""2次元ベクトルの小さなユーティリティ

形状ごとの *_func.py が共通で使う。
同じ関数を3ファイルに複製しないためにここへ切り出している。
"""

import numpy as np


def norm2(v):
    """2次元ベクトルのノルム。np.linalg.norm の置き換え。

    高速化の理由:
      np.linalg.norm は ravel / 汎用軸処理 / dot を経由するため、
      2成分ベクトルではオーバーヘッドが支配的になる。
      cProfile で測ったところ、スタジアムの軌道計算(20000衝突)の
      約33%がこの関数呼び出しに消えていた。

    安全性:
      np.linalg.norm(v) の中身は sqrt(dot(v, v)) なので、2成分なら
      sqrt(x*x + y*y) と結果がビット単位で完全に一致する（確認済み）。
      実測で約2.2倍速い。

    math.hypot を使わない理由:
      さらに約5倍速いが、より高精度なアルゴリズムを使っているため
      np.linalg.norm と 1 ULP ずれる。ビリヤードはカオス系なので、
      最下位ビットのずれが数十衝突後には軌道を丸ごと変えてしまい、
      過去に出した図と再現が取れなくなる。速度より再現性を優先する。
    """
    return np.sqrt(v[0] * v[0] + v[1] * v[1])
